"""Command-line entry point for recomputing and verifying evaluation metrics.

The repository commits ``evaluation_results.pkl`` and a ``final_report.txt``
generated by a pipeline that is no longer part of the tree, so the report's
numbers cannot be checked from the code alone. This CLI recomputes them from the
stored per-sample arrays:

    python -m uce.cli report --results evaluation_results.pkl
    python -m uce.cli verify --results evaluation_results.pkl
    python -m uce.cli report --results evaluation_results.pkl --json

``verify`` compares recomputed values with the stored ones and exits non-zero on
any mismatch, which makes the committed report a testable claim.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import pickle
import sys
from pathlib import Path

import numpy as np

from uce.metrics import (
    accuracy_in_top_quantile,
    error_correlation,
    expected_calibration_error,
    fpr_at_95_tpr,
    ood_detection_auroc,
    pearson_correlation,
    spearman_correlation,
)

# Reconstructing data is allowed; executing anything else is not. The artefact
# is only trusted after its checksum is verified (see tests/test_report.py).
_ALLOWED_PICKLE_PREFIXES = ("numpy", "collections")
_ALLOWED_BUILTINS = {"dict", "list", "tuple", "set", "frozenset", "str", "bytes", "int", "float"}

# (column heading, key in the recomputed row) - the headings mirror
# final_report.txt so the output can be diffed against the committed report.
STANDARD_COLUMNS = (
    ("Accuracy", "accuracy"),
    ("ECE", "ece"),
    ("AUROC", "ood_auroc"),
    ("FPR95", "ood_fpr95"),
)
UNSUPERVISED_COLUMNS = (
    ("Spearman Corr", "unsupervised_spearman"),
    ("Q4 Accuracy", "q4_accuracy"),
)

# Tolerance when comparing recomputed values with the stored ones: the artefact
# stores float32 confidences, so agreement is close but not bit-exact.
VERIFY_ATOL = 5e-4


class _RestrictedUnpickler(pickle.Unpickler):
    """Unpickler that refuses globals outside a small data-only allowlist."""

    def find_class(self, module: str, name: str):
        if module == "builtins" and name in _ALLOWED_BUILTINS:
            import builtins

            return getattr(builtins, name)
        if any(module == p or module.startswith(p + ".") for p in _ALLOWED_PICKLE_PREFIXES):
            return super().find_class(module, name)
        raise pickle.UnpicklingError(
            f"Refusing to unpickle global {module}.{name} from a results artefact"
        )


def load_results(path: str | Path) -> dict:
    """Load an evaluation-results pickle with a data-only unpickler."""
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"results file not found: {path}")
    return _RestrictedUnpickler(io.BytesIO(path.read_bytes())).load()


def file_sha256(path: str | Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _correctness(predictions: np.ndarray, labels: np.ndarray) -> np.ndarray:
    return np.asarray(predictions) == np.asarray(labels)


def _model_rows(results: dict) -> dict[str, dict]:
    """Recompute the report's per-method metrics from the stored arrays."""
    standard = results.get("standard_results", {})
    unsupervised = results.get("unsupervised_results", {})
    rows: dict[str, dict] = {}

    for model, row in standard.items():
        confidences = np.asarray(row["id_confidences"], dtype=np.float64)
        correct = _correctness(row["predictions"], row["labels"])
        # The report's per-method columns use the *uncertainty vs error* sign
        # convention, so both coefficients are taken against the error signal
        # even though a confidence-vs-correctness reading is more intuitive.
        errors = ~correct
        metrics: dict[str, float] = {
            "accuracy": float(correct.mean() * 100.0),
            "ece": expected_calibration_error(confidences, correct),
            "spearman_corr": error_correlation(confidences, correct).statistic,
            "pearson_corr": pearson_correlation(confidences, errors).statistic,
        }
        ood_confidences = row.get("ood_confidences")
        if ood_confidences is not None:
            metrics["ood_auroc"] = ood_detection_auroc(confidences, ood_confidences)
            metrics["ood_fpr95"] = fpr_at_95_tpr(confidences, ood_confidences)

        unsup = unsupervised.get(model)
        if unsup:
            final_confidence = np.asarray(unsup["final_confidence"], dtype=np.float64)
            unsup_correct = ~np.asarray(unsup["errors"]).astype(bool)
            # The unsupervised section reports the (higher-is-better) score vs
            # correctness sign, which is the opposite of the standard section.
            metrics["unsupervised_spearman"] = spearman_correlation(
                final_confidence, unsup_correct
            ).statistic
            metrics["unsupervised_pearson"] = pearson_correlation(
                final_confidence, unsup_correct
            ).statistic
            metrics["q4_accuracy"] = accuracy_in_top_quantile(
                final_confidence, unsup_correct
            )
        rows[str(model)] = metrics
    return rows


def _print_table(rows: dict[str, dict], columns: tuple[tuple[str, str], ...]) -> None:
    width = max(len(name) for name in rows) if rows else 4
    header = f"{'Method':<{width}}  " + "  ".join(f"{label:>16}" for label, _ in columns)
    print(header)
    print("-" * len(header))
    for model, metrics in rows.items():
        cells = []
        for _, key in columns:
            value = metrics.get(key)
            cells.append(f"{value:>16.4f}" if isinstance(value, (int, float)) else f"{'-':>16}")
        print(f"{model:<{width}}  " + "  ".join(cells))


def cmd_report(args: argparse.Namespace) -> int:
    results = load_results(args.results)
    rows = _model_rows(results)

    if args.json:
        print(json.dumps({"sha256": file_sha256(args.results), "models": rows}, indent=2))
        return 0

    print(f"Recomputed from {args.results} (sha256 {file_sha256(args.results)[:12]}...)")
    print("\nMODEL PERFORMANCE SUMMARY")
    _print_table(rows, STANDARD_COLUMNS)
    print("\nUNSUPERVISED METRIC PERFORMANCE")
    _print_table(rows, UNSUPERVISED_COLUMNS)
    return 0


def cmd_verify(args: argparse.Namespace) -> int:
    """Recompute stored metrics and fail when the artefact disagrees with itself."""
    results = load_results(args.results)
    rows = _model_rows(results)
    standard = results.get("standard_results", {})
    unsupervised = results.get("unsupervised_results", {})

    checks: list[tuple[str, str, float, float]] = []
    for model, metrics in rows.items():
        stored_standard = standard.get(model, {})
        for key in ("accuracy", "ece", "spearman_corr", "pearson_corr", "ood_auroc", "ood_fpr95"):
            if key in stored_standard and key in metrics:
                checks.append((model, key, float(stored_standard[key]), metrics[key]))
        stored_unsup = unsupervised.get(model, {})
        for key in ("spearman_corr", "pearson_corr"):
            if key in stored_unsup:
                computed = metrics.get(f"unsupervised_{key}")
                if computed is not None:
                    checks.append((model, f"unsupervised.{key}", float(stored_unsup[key]), computed))

    failures = [
        (model, key, stored, computed)
        for model, key, stored, computed in checks
        if not np.isclose(stored, computed, atol=args.atol)
    ]

    for model, key, stored, computed in checks:
        if (model, key, stored, computed) not in failures:
            continue
        print(f"MISMATCH {model}.{key}: stored={stored:.6f} recomputed={computed:.6f}")
    print(f"Checked {len(checks)} stored metric(s); {len(failures)} mismatch(es).")
    if failures:
        return 1
    print("OK: the results artefact is consistent with uce.metrics.")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="uce",
        description="Recompute/verify UCE evaluation metrics from a results artefact.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    default_results = "evaluation_results.pkl"

    report = subparsers.add_parser("report", help="Print metrics recomputed from an artefact")
    report.add_argument("--results", default=default_results, help="Path to the results pickle")
    report.add_argument("--json", action="store_true", help="Emit JSON instead of tables")
    report.set_defaults(func=cmd_report)

    verify = subparsers.add_parser(
        "verify", help="Check stored metrics against recomputed ones (exit 1 on mismatch)"
    )
    verify.add_argument("--results", default=default_results, help="Path to the results pickle")
    verify.add_argument(
        "--atol", type=float, default=VERIFY_ATOL, help="Absolute tolerance for agreement"
    )
    verify.set_defaults(func=cmd_verify)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
